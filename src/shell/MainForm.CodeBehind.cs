        // ---- the layout behind a code file, whether or not it is open in a tab
        sealed class LayoutRef { internal KernelDocument Document; internal EditorPage Page; internal bool Opened; internal string Path; }
        LayoutRef OpenLayout(string layout)
        {
            var page=Pages.FirstOrDefault(p=>String.Equals(p.Document.PathName,layout,StringComparison.OrdinalIgnoreCase));
            if(page!=null) return new LayoutRef { Document=page.Document, Page=page, Path=layout };
            bool already; var document=KernelDocument.Open(Kernel,layout,out already);
            return new LayoutRef { Document=document, Opened=!already, Path=layout };
        }
        // An unsaved layout is only reachable through its page; a saved one also by path.
        LayoutRef LayoutFor(CodeBarState state)
        {
            var page=state.LayoutPage;
            if(page!=null && !page.IsDisposed && Pages.Contains(page)) return new LayoutRef { Document=page.Document, Page=page, Path=page.Document.PathName };
            if(state.Layout==null) throw new InvalidOperationException("这段代码所属的窗体已经关闭。");
            return OpenLayout(state.Layout);
        }
        EditorPage LinkedCode(EditorPage layout) { return layout==null ? null : Pages.FirstOrDefault(p=>p.CodeBar!=null && p.CodeBar.LayoutPage==layout); }
        void Release(LayoutRef layout) { if(layout.Opened && layout.Page==null && Pages.All(p=>p.Document.Id!=layout.Document.Id)) layout.Document.Close(ClosePolicy.Discard); }
        static string LayoutOf(string code)
        {
            if(code==null) return null; string ext=Path.GetExtension(code).ToLowerInvariant(); if(ext!=".cs" && ext!=".vb") return null;
            string stem=Path.Combine(Path.GetDirectoryName(code),Path.GetFileNameWithoutExtension(code));
            if(stem.EndsWith(".Designer",StringComparison.OrdinalIgnoreCase)) return null;
            return File.Exists(stem+".omform") ? stem+".omform" : null;
        }

        // ---- double-click in the designer
        void ActivateDesign(EditorPage page,DesignItem item)
        {
            if(page.Designer.Html) {
                if(item==null) return;
