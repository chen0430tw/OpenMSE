        // Inserts an empty procedure into the user's class when missing; returns the caret index inside it.
        int EnsureHandler(EditorPage page,string cls,string handler,string args,bool vb)
        {
            string text=page.Document.Shadow;
            var found=FindProcedure(text,handler,vb);
            if(found>=0) { int next=text.IndexOf('\n',found); if(!vb && next>=0) { int brace=text.IndexOf('{',found); int after=brace<0 ? -1 : text.IndexOf('\n',brace); if(after>=0) next=after; } return next<0 ? found : Indented(text,next+1); }
            var options=vb ? RegexOptions.IgnoreCase : RegexOptions.None;
            var start=Regex.Match(text,vb ? @"\bClass\s+\[?"+Regex.Escape(cls)+@"\]?(?!\w)" : @"\bclass\s+@?"+Regex.Escape(cls)+@"(?!\w)",options);
            int end=!start.Success ? -1 : vb ? EndOfVbClass(text,start.Index) : EndOfCSharpClass(text,start.Index);
            if(end<0) throw new InvalidOperationException(Path.GetFileName(page.Document.PathName)+" 中没有可以写入的 "+cls+" 类，未作修改。");
            string before=vb ? "\n    Private Sub "+handler+"(ByVal sender As Object, ByVal e As "+args+")\n        " : "\n    private void "+handler+"(object sender, "+args+" e)\n    {\n        ";
            page.Editor.Text=text.Insert(end,before+(vb ? "\n    End Sub\n" : "\n    }\n"));
            return end+before.Length;
        }
        static int FindProcedure(string text,string handler,bool vb)
        {
            var m=Regex.Match(text,vb ? @"\bSub\s+\[?"+Regex.Escape(handler)+@"\]?\s*\(" : @"\bvoid\s+@?"+Regex.Escape(handler)+@"\s*\(",vb ? RegexOptions.IgnoreCase : RegexOptions.None);
            return m.Success ? m.Index : -1;
        }
        // Name of the procedure that contains the index, or null.
        static string ProcedureAt(string text,int index,bool vb)
        {
            string before=text.Substring(0,Math.Min(index,text.Length));
            var all=Regex.Matches(before,vb ? @"\b(?:Sub|Function)\s+\[?(\w+)\]?\s*\(" : @"\bvoid\s+@?(\w+)\s*\(",vb ? RegexOptions.IgnoreCase : RegexOptions.None);
            if(all.Count==0) return null; var last=all[all.Count-1];
            string rest=before.Substring(last.Index);
            // C#: still on the header line (no brace yet), or inside the body.
            if(vb ? Regex.IsMatch(rest,@"\bEnd\s+(Sub|Function)\b",RegexOptions.IgnoreCase) : rest.IndexOf('{')>=0 && rest.Count(c=>c=='{')<=rest.Count(c=>c=='}')) return null;
            return last.Groups[1].Value;
        }
        static int Indented(string text,int index) { while(index<text.Length && (text[index]==' ' || text[index]=='\t')) index++; return index; }
        static int EndOfVbClass(string text,int start)
        {
            int depth=0;
            foreach(Match m in Regex.Matches(text.Substring(start),@"^(?<end>[ \t]*End[ \t]+Class\b)|^[^'""\n]*\bClass[ \t]+\[?\w",RegexOptions.IgnoreCase|RegexOptions.Multiline)) {
                if(m.Groups["end"].Success) { if(--depth==0) return start+m.Index; } else depth++;
            }
            return -1;
        }
        // Start of the line holding the class's closing brace; strings, characters and comments are skipped.
        static int EndOfCSharpClass(string text,int start)
        {
            int depth=0;
            for(int i=start;i<text.Length;i++) {
                char c=text[i];
                if(c=='/' && i+1<text.Length && text[i+1]=='/') { i=text.IndexOf('\n',i); if(i<0) return -1; }
                else if(c=='/' && i+1<text.Length && text[i+1]=='*') { i=text.IndexOf("*/",i+2,StringComparison.Ordinal); if(i<0) return -1; i++; }
                else if(c=='@' && i+1<text.Length && text[i+1]=='"') { for(i+=2;i<text.Length;i++) if(text[i]=='"') { if(i+1<text.Length && text[i+1]=='"') i++; else break; } }
                else if(c=='"' || c=='\'') { for(int q=i+1;q<text.Length;q++) { if(text[q]=='\\') q++; else if(text[q]==c || text[q]=='\n') { i=q; break; } } }
                else if(c=='{') depth++;
                else if(c=='}' && --depth==0) { int line=text.LastIndexOf('\n',i)+1; return text.Substring(line,i-line).Trim().Length==0 ? line : i; }
            }
            return -1;
        }

        // ---- object and event lists above a form's code window (as in the VB/VBA code window)
        internal sealed class CodeBarState
        {
            internal string Layout, ClassName; internal bool VisualBasic;
            internal EditorPage LayoutPage;   // set while the layout is open (required while it is unsaved)
            internal ComboBox Objects, Events; internal bool Updating;
            internal Dictionary<string,HashSet<string>> Bound=new Dictionary<string,HashSet<string>>();
            internal Dictionary<string,string> Kinds=new Dictionary<string,string>();
            internal Dictionary<string,KeyValuePair<string,string>> ByHandler=new Dictionary<string,KeyValuePair<string,string>>(StringComparer.OrdinalIgnoreCase);
        }
        sealed class ObjectChoice { internal string Name, Label; public override string ToString() { return Label; } }
        void AttachCodeBar(EditorPage page,EditorPage layoutPage=null)
        {
            string layout=layoutPage!=null ? layoutPage.Document.PathName : LayoutOf(page.Document.PathName);
            if((layout==null && layoutPage==null) || page.CodeBar!=null) return;
            string own=page.Document.PathName ?? page.Document.Name;
            var state=new CodeBarState { Layout=layout, LayoutPage=layoutPage ?? Pages.FirstOrDefault(p=>layout!=null && String.Equals(p.Document.PathName,layout,StringComparison.OrdinalIgnoreCase)),
                ClassName=ClassName(layout ?? layoutPage.UntitledName), VisualBasic=own.EndsWith(".vb",StringComparison.OrdinalIgnoreCase) };
            var bar=new TableLayoutPanel { Dock=DockStyle.Top, Height=34, ColumnCount=2, RowCount=1, Padding=new Padding(0,2,8,4), BackColor=Color.FromArgb(243,246,251) };
            bar.ColumnStyles.Add(new ColumnStyle(SizeType.Percent,45)); bar.ColumnStyles.Add(new ColumnStyle(SizeType.Percent,55));
            state.Objects=new ComboBox { Dock=DockStyle.Fill, DropDownStyle=ComboBoxStyle.DropDownList, MaxDropDownItems=24 };
            state.Events=new ComboBox { Dock=DockStyle.Fill, DropDownStyle=ComboBoxStyle.DropDownList, DrawMode=DrawMode.OwnerDrawFixed, MaxDropDownItems=24 };
            // Events that already have a procedure are bold, as in the VB editor.
            state.Events.DrawItem+=delegate(object sender,DrawItemEventArgs e) {
                e.DrawBackground(); if(e.Index<0) return; var ev=(EventCatalog.Entry)state.Events.Items[e.Index]; var obj=state.Objects.SelectedItem as ObjectChoice;
                bool bound=obj!=null && state.Bound.ContainsKey(obj.Name) && state.Bound[obj.Name].Contains(ev.Name);
                using(var font=new Font(e.Font,bound ? FontStyle.Bold : FontStyle.Regular)) TextRenderer.DrawText(e.Graphics,ev.Name,font,e.Bounds,(e.State & DrawItemState.Selected)!=0 ? SystemColors.HighlightText : SystemColors.ControlText,TextFormatFlags.VerticalCenter|TextFormatFlags.Left);
            };
            state.Objects.SelectedIndexChanged+=delegate { if(!state.Updating) FillEvents(state); };
            state.Events.SelectionChangeCommitted+=delegate { Guard(delegate { ChooseEvent(page,((ObjectChoice)state.Objects.SelectedItem).Name,((EventCatalog.Entry)state.Events.SelectedItem).Name); }); };
            bar.Controls.Add(state.Objects,0,0); bar.Controls.Add(state.Events,1,0);
            page.CodeBar=state; page.Controls.Add(bar); page.Editor.BringToFront();
            page.Editor.SelectionChanged+=delegate { if(page.CodeBar!=null && !state.Updating) SyncCodeBar(page); };
            RefreshCodeBar(page);
        }
        internal void RefreshCodeBar(EditorPage page)
        {
            var state=page.CodeBar; if(state==null) return;
            if((state.LayoutPage==null || state.LayoutPage.IsDisposed) && (state.Layout==null || !File.Exists(state.Layout))) return;
            var layout=LayoutFor(state);
            try {
                var design=layout.Document.Design(); if(design.Error!=null) return;
                string selected=state.Objects.SelectedItem is ObjectChoice ? ((ObjectChoice)state.Objects.SelectedItem).Name : "";
                state.Updating=true;
                state.Bound.Clear(); state.Kinds.Clear(); state.ByHandler.Clear(); state.Objects.Items.Clear();
                Action<string,string,string,Dictionary<string,string>> add=delegate(string name,string label,string kind,Dictionary<string,string> handlers) {
                    state.Objects.Items.Add(new ObjectChoice { Name=name, Label=label }); state.Kinds[name]=kind;
                    state.Bound[name]=new HashSet<string>(handlers.Keys);
                    foreach(var h in handlers) state.ByHandler[h.Value]=new KeyValuePair<string,string>(name,h.Key);
                };
                add("",state.ClassName+"（窗体）","Form",design.FormHandlers);
                foreach(var n in design.Nodes) add(n.Name,n.Name+"（"+n.Kind+"）",n.Kind,n.Handlers);
                state.Objects.SelectedItem=state.Objects.Items.Cast<ObjectChoice>().FirstOrDefault(o=>o.Name==selected) ?? state.Objects.Items[0];
                FillEvents(state);
            } finally { state.Updating=false; Release(layout); }
            SyncCodeBar(page);
        }
        void FillEvents(CodeBarState state)
        {
            var obj=state.Objects.SelectedItem as ObjectChoice; state.Events.Items.Clear(); if(obj==null) return;
            foreach(var e in EventCatalog.For(state.Kinds[obj.Name])) state.Events.Items.Add(e);
        }
        // The two lists follow the caret: inside button2_Click they show button2 / Click.
        void SyncCodeBar(EditorPage page)
        {
            var state=page.CodeBar; if(state==null) return;
            string procedure=ProcedureAt(page.Document.Shadow,page.Editor.SelectionStart,state.VisualBasic);
            KeyValuePair<string,string> target;
            if(procedure==null || !state.ByHandler.TryGetValue(procedure,out target)) return;
            state.Updating=true;
            try {
                var obj=state.Objects.Items.Cast<ObjectChoice>().FirstOrDefault(o=>o.Name==target.Key);
                if(obj!=null && state.Objects.SelectedItem!=obj) { state.Objects.SelectedItem=obj; FillEvents(state); }
                state.Events.SelectedItem=state.Events.Items.Cast<EventCatalog.Entry>().FirstOrDefault(e=>e.Name==target.Value);
            } finally { state.Updating=false; }
        }
        // Same as picking an object and an event in the two lists.
        internal void ChooseEvent(EditorPage page,string objectName,string eventName)
        {
            var state=page.CodeBar; if(state==null) throw new InvalidOperationException("这不是窗体的代码文件。");
            var entry=EventCatalog.For(state.Kinds[objectName]).FirstOrDefault(e=>e.Name==eventName);
            if(entry==null) throw new InvalidOperationException(eventName+" 不是该对象的事件。");
            OpenEvent(LayoutFor(state),objectName.Length==0 ? null : objectName,eventName,entry.Args);
        }
        internal IList<string> EventNames(EditorPage page,string objectName,bool boundOnly)
        {
            var state=page.CodeBar; return EventCatalog.For(state.Kinds[objectName]).Select(e=>e.Name).Where(n=>!boundOnly || state.Bound[objectName].Contains(n)).ToList();
        }

        // Rewrites the generated half. Never replaces a file this designer did not generate.
        void Generate(KernelDocument layout,string layoutPath,bool vb,bool create)
        {
            string path=Path.Combine(Path.GetDirectoryName(layoutPath),Path.GetFileNameWithoutExtension(layoutPath))+".Designer"+(vb ? ".vb" : ".cs");
            if(!File.Exists(path)) { if(!create) return; }
            else if(!File.ReadAllText(path).Contains(GeneratedMark)) { if(!create) return; throw new IOException(Path.GetFileName(path)+" 不是由 OpenMSE 生成的，已保留，未覆盖。"); }
            WriteFile(path,layout.GenerateDesign(vb,ClassName(layoutPath)));
        }
        void RegenerateAfterSave(EditorPage page)
        {
            if(page.Designer==null || page.Designer.Html || page.Designer.ErrorMessage!=null || !String.Equals(Path.GetExtension(page.Document.PathName),".omform",StringComparison.OrdinalIgnoreCase)) return;
            // First save of a form whose code was written before it had a file: the code follows it.
            var linked=LinkedCode(page);
            if(linked!=null && linked.Document.PathName==null) {
                string layout=page.Document.PathName, stem=Path.Combine(Path.GetDirectoryName(layout),Path.GetFileNameWithoutExtension(layout));
                bool vb=linked.CodeBar.VisualBasic; string code=stem+(vb ? ".vb" : ".cs"), cls=ClassName(layout);
                if(File.Exists(code)) throw new IOException("窗体已保存，但 "+Path.GetFileName(code)+" 已存在，未覆盖；代码仍在未命名标签“"+linked.UntitledName+"”中。");
                if(cls!=linked.CodeBar.ClassName)
                    linked.Editor.Text=Regex.Replace(linked.Document.Shadow,@"(?<![\p{L}\p{Nd}_])"+Regex.Escape(linked.CodeBar.ClassName)+@"(?![\p{L}\p{Nd}_])",cls);
                linked.CodeBar.Layout=layout; linked.CodeBar.ClassName=cls;
                SaveTo(linked,code);
                Generate(page.Document,layout,vb,true);
                AddToProject(layout,code,stem+".Designer"+(vb ? ".vb" : ".cs"));
            }
            Generate(page.Document,page.Document.PathName,false,false); Generate(page.Document,page.Document.PathName,true,false);
            foreach(var code in Pages.Where(p=>p.CodeBar!=null && (p.CodeBar.LayoutPage==page || String.Equals(p.CodeBar.Layout,page.Document.PathName,StringComparison.OrdinalIgnoreCase))).ToList()) RefreshCodeBar(code);
        }
        void WriteFile(string path,string text)
        {
            text=KernelDocument.Normalize(text);
            var open=Pages.FirstOrDefault(p=>String.Equals(p.Document.PathName,path,StringComparison.OrdinalIgnoreCase));
            if(open!=null) { if(open.Document.Shadow!=text) open.Editor.Text=text; if(open.Dirty) SaveTo(open,null); return; }
            if(File.Exists(path) && KernelDocument.Normalize(File.ReadAllText(path))==text) return;
            var document=KernelDocument.Create(Kernel,Path.GetFileName(path),text);
            try { document.Save(path); } finally { document.Close(ClosePolicy.Discard); }
        }

        // As in Visual Studio, a form's files join the project that contains them.
        void AddToProject(string layout,string code,string designer)
        {
            var project=OwningProject(layout); bool vb=code.EndsWith(".vb",StringComparison.OrdinalIgnoreCase);
            if(project==null || project.Kind!=(vb ? "vb" : "csharp")) { status.Text="窗体代码已生成；布局不在已打开的项目中，未加入项目。"; return; }
            string folder=Path.GetDirectoryName(project.Path)+"\\"; Func<string,string> include=f=>SecurityElement.Escape(f.Substring(folder.Length));
            bool already; var document=KernelDocument.Open(Kernel,project.Path,out already);
            try {
                string text=document.Shadow, items="";
                Func<string,bool> has=f=>Regex.IsMatch(text,"Include\\s*=\\s*\""+Regex.Escape(include(f))+"\"",RegexOptions.IgnoreCase);
                foreach(string reference in new[]{"System.Drawing","System.Windows.Forms"}) if(!Regex.IsMatch(text,"<Reference\\s+Include\\s*=\\s*\""+Regex.Escape(reference)+"[\",]",RegexOptions.IgnoreCase)) items+="    <Reference Include=\""+reference+"\" />\n";
                if(!has(code)) items+="    <Compile Include=\""+include(code)+"\">\n      <SubType>Form</SubType>\n    </Compile>\n";
                if(!has(designer)) items+="    <Compile Include=\""+include(designer)+"\">\n      <DependentUpon>"+SecurityElement.Escape(Path.GetFileName(code))+"</DependentUpon>\n    </Compile>\n";
                if(!has(layout)) items+="    <None Include=\""+include(layout)+"\" />\n";
                if(items.Length==0) return;
                int at=text.IndexOf("  <Import ",StringComparison.Ordinal); if(at<0) at=text.LastIndexOf("</Project>",StringComparison.Ordinal);
                if(at<0) throw new InvalidOperationException("项目文件结构无法识别，未加入窗体。");
                document.Sync(text.Insert(at,"  <ItemGroup>\n"+items+"  </ItemGroup>\n"),false); document.Save(null);
            } finally { if(!already) document.Close(ClosePolicy.Discard); }
            string configuration=Configuration; OpenProject(Workspace.Path); if(configuration!=null) Configuration=configuration;
            status.Text="窗体已加入项目 "+project.Name;
        }
    }

    // Events of the .NET 2.0 Windows Forms types the generated code targets, read without loading them for execution.
    internal static class EventCatalog
    {
        internal sealed class Entry { internal string Name, Args; public override string ToString() { return Name; } }
        static readonly Dictionary<string,List<Entry>> cache=new Dictionary<string,List<Entry>>();
        static Assembly forms;
        static Assembly Forms()
        {
            if(forms!=null) return forms;
            string dir=Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Windows),@"Microsoft.NET\Framework\v2.0.50727");
            try {
                AppDomain.CurrentDomain.ReflectionOnlyAssemblyResolve+=delegate(object sender,ResolveEventArgs e) {
                    string file=Path.Combine(dir,new AssemblyName(e.Name).Name+".dll");
                    return File.Exists(file) ? Assembly.ReflectionOnlyLoadFrom(file) : Assembly.ReflectionOnlyLoad(e.Name);
                };
                forms=Assembly.ReflectionOnlyLoadFrom(Path.Combine(dir,"System.Windows.Forms.dll"));
            } catch(Exception) { forms=typeof(Form).Assembly; }   // no .NET 2.0: the running version's list
            return forms;
        }
        internal static IList<Entry> For(string kind)
        {
            List<Entry> list;
            if(cache.TryGetValue(kind,out list)) return list;
            var type=Forms().GetType("System.Windows.Forms."+kind) ?? typeof(Form).Assembly.GetType("System.Windows.Forms."+kind);
            list=new List<Entry>();
            if(type!=null) foreach(var e in type.GetEvents(BindingFlags.Public|BindingFlags.Instance)) {
                // Events hidden from designers and IntelliSense are not offered.
                bool hidden=CustomAttributeData.GetCustomAttributes(e).Any(a=>(a.Constructor.DeclaringType.Name=="BrowsableAttribute" && a.ConstructorArguments.Count==1 && false.Equals(a.ConstructorArguments[0].Value))
                    || (a.Constructor.DeclaringType.Name=="EditorBrowsableAttribute" && a.ConstructorArguments.Count==1 && Convert.ToInt32(a.ConstructorArguments[0].Value)==(int)EditorBrowsableState.Never));
                if(hidden) continue;
                var invoke=e.EventHandlerType.GetMethod("Invoke"); var args=invoke==null ? null : invoke.GetParameters();
                list.Add(new Entry { Name=e.Name, Args=args!=null && args.Length==2 ? args[1].ParameterType.FullName : "System.EventArgs" });
            }
            list=list.GroupBy(e=>e.Name).Select(g=>g.First()).OrderBy(e=>e.Name,StringComparer.Ordinal).ToList();
            cache[kind]=list;
            return list;
        }
    }
