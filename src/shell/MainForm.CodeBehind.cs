        }

        // Goes to the procedure for one object's event, creating and binding it when it does not exist yet.
        void OpenEvent(LayoutRef layout,string objectName,string eventName,string argsType)
        {
            if(BuildRunning) throw new InvalidOperationException("生成或运行进行中，请稍后再编辑窗体事件。");
            string layoutPath=layout.Path, layoutName=layoutPath ?? layout.Page.UntitledName;
            var linked=LinkedCode(layout.Page);
            bool? language=linked!=null ? linked.CodeBar.VisualBasic : CodeLanguage(layoutPath,layoutName); if(language==null) return; bool vb=language.Value;
            string ext=vb ? ".vb" : ".cs", cls=ClassName(layoutName);
            string stem=layoutPath==null ? null : Path.Combine(Path.GetDirectoryName(layoutPath),Path.GetFileNameWithoutExtension(layoutPath)), code=stem==null ? null : stem+ext;
            try {
                var design=layout.Document.Design(); if(design.Error!=null) throw new InvalidOperationException(design.Error);
                var item=objectName==null ? null : design.Nodes.First(n=>n.Name==objectName);
                var handlers=item==null ? design.FormHandlers : item.Handlers; string handler;
                bool bind=!handlers.TryGetValue(eventName,out handler);
                if(bind) handler=(objectName ?? cls)+"_"+eventName;
                string skeleton=vb
                    ? "Partial Public Class "+cls+"\n    Public Sub New()\n        InitializeComponent()\n    End Sub\nEnd Class\n"
                    : "public partial class "+cls+"\n{\n    public "+cls+"()\n    {\n        InitializeComponent();\n    }\n}\n";
                EditorPage editor;
                if(linked!=null) editor=linked;
                else if(code==null) {
                    editor=new EditorPage(KernelDocument.Create(Kernel,Path.GetFileNameWithoutExtension(layoutName)+ext,skeleton)); AddEditor(editor); AttachCodeBar(editor,layout.Page);
                } else {
                    if(!File.Exists(code)) WriteFile(code,skeleton);
                    OpenFile(code); editor=Active; if(editor.CodeBar!=null) editor.CodeBar.LayoutPage=layout.Page;
                }
                int at=EnsureHandler(editor,cls,handler,argsType,vb);
                if(bind) {
                    var op=new Dictionary<string,object> { {"op","set_event"}, {"node",item==null ? "form" : item.NodeId}, {"handler",handler}, {"event",eventName} };
                    if(layout.Page!=null) layout.Page.Designer.SetEvent(item==null ? "form" : item.NodeId,handler,eventName);
                    else { bool changed; int i,l; string t; layout.Document.ApplyDesign(op,layout.Document.Revision,out changed,out i,out l,out t); }
                }
                if(layoutPath!=null) {
                    if(layout.Page!=null) SaveTo(layout.Page,null); else if(layout.Document.Dirty) layout.Document.Save(null);
                    Generate(layout.Document,layoutPath,vb,true);
                    AddToProject(layoutPath,code,stem+".Designer"+ext);
                } else status.Text="窗体尚未保存：保存窗体时，代码会一并保存到它旁边。";
                Tabs.SelectedTab=editor; RefreshCodeBar(editor);
                // Show the whole procedure from its first line, with the caret inside it.
                int header=editor.Document.Shadow.LastIndexOf('\n',Math.Max(0,Math.Min(editor.Document.Shadow.Length-1,at-1)));
                header=editor.Document.Shadow.LastIndexOf('\n',Math.Max(0,header-1))+1;
                editor.Editor.Select(editor.Editor.TextLength,0); editor.Editor.ScrollToCaret(); editor.Editor.Select(header,0); editor.Editor.ScrollToCaret();
                editor.Editor.Select(at,0); editor.Editor.Focus(); SyncCodeBar(editor);
            } finally { Release(layout); }
        }
